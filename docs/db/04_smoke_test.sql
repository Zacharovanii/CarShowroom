    tmp_id bigint;
begin
    insert into cars (series_id, body_type_id, fuel_type_id, slug, name, model_year,
                      description, drive_type, power_hp, acceleration_s, top_speed_kmh, price)
    values (1, 1, 1, 'tmp-car', 'Tmp Car', 2026, 'X', 'rwd', 100, 9.9, 200, 1000000)
