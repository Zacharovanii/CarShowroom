CREATE VIEW public.catalog_items AS
 SELECT c.id,
    c.slug,
    c.name,
    c.model_year,
    c.price,
    c.drive_type,
    c.power_hp,
    c.created_at,
    c.series_id,
    s.name AS series_name,
    c.body_type_id,
    bt.name AS body_type_name,
    c.fuel_type_id,
    ft.name AS fuel_type_name,
    cover.path AS cover_path,
    cover.alt AS cover_alt,
    (c.model_3d_path IS NOT NULL) AS has_3d
   FROM ((((public.cars c
     JOIN public.series s ON ((s.id = c.series_id)))
     JOIN public.body_types bt ON ((bt.id = c.body_type_id)))
     JOIN public.fuel_types ft ON ((ft.id = c.fuel_type_id)))
     LEFT JOIN LATERAL ( SELECT i.path,
            i.alt
           FROM public.car_images i
          WHERE (i.car_id = c.id)
          ORDER BY i."position"
         LIMIT 1) cover ON (true))
  WHERE c.is_published;


